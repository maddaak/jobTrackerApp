-- Separate job hunts. Every account gets one season holding all the jobs it already has.

CREATE TABLE seasons (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES users (id),
    name varchar(100) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL
);

CREATE INDEX idx_seasons_owner_id ON seasons (owner_id);

INSERT INTO seasons (owner_id, name, created_at) SELECT id, 'My job hunt', created_at FROM users;

-- Added nullable, backfilled, then constrained, since a populated table can't take a NOT NULL column.
ALTER TABLE jobs ADD COLUMN season_id bigint;
UPDATE jobs SET season_id = (SELECT seasons.id FROM seasons WHERE seasons.owner_id = jobs.owner_id);
ALTER TABLE jobs ALTER COLUMN season_id SET NOT NULL;
ALTER TABLE jobs ADD CONSTRAINT fk_jobs_season FOREIGN KEY (season_id) REFERENCES seasons (id);
CREATE INDEX idx_jobs_season_id ON jobs (season_id);

-- Null means the account is looking at every season at once.
ALTER TABLE users ADD COLUMN active_season_id bigint;
UPDATE users SET active_season_id = (SELECT seasons.id FROM seasons WHERE seasons.owner_id = users.id);
ALTER TABLE users ADD CONSTRAINT fk_users_active_season FOREIGN KEY (active_season_id) REFERENCES seasons (id);
