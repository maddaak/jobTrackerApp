-- The schema as of V4.0.0, written so it also runs over a database Hibernate created before Flyway:
-- every statement is a no-op where the table or column is already there.
-- Enum CHECK constraints are not here; EnumCheckConstraints writes them from the Java enums at startup.

CREATE TABLE IF NOT EXISTS users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(255) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    name varchar(255),
    email varchar(255),
    created_at timestamp(6) with time zone NOT NULL
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS name varchar(255);
ALTER TABLE users ADD COLUMN IF NOT EXISTS email varchar(255);

CREATE TABLE IF NOT EXISTS jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES users (id),
    company varchar(255) NOT NULL,
    role varchar(255) NOT NULL,
    source_category varchar(255) NOT NULL,
    current_stage varchar(255) NOT NULL,
    interview_phase varchar(255),
    outcome varchar(255) NOT NULL,
    url text,
    location varchar(255),
    city varchar(100),
    comp_min integer,
    comp_max integer,
    created_at timestamp(6) with time zone NOT NULL
);

-- No source_category here: its absence is how V3Migration recognises a pre-v3 database.
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS interview_phase varchar(255);
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS location varchar(255);
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS city varchar(100);
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS comp_min integer;
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS comp_max integer;
-- Hibernate never widened this on a database it created before the entity asked for text.
ALTER TABLE jobs ALTER COLUMN url SET DATA TYPE text;

CREATE INDEX IF NOT EXISTS idx_jobs_owner_id ON jobs (owner_id);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    token_hash varchar(255) NOT NULL UNIQUE,
    expires_at timestamp(6) with time zone NOT NULL,
    used_at timestamp(6) with time zone
);
