package com.jobtracker.core.config;

import org.flywaydb.core.Flyway;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.support.PathMatchingResourcePatternResolver;

import javax.sql.DataSource;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

// Every install before Flyway has a schema Hibernate made and no history table; this is the path they all take.
class FlywayUpgradeTests {

    private DataSource freshDatabase() {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:flyway-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1");
        dataSource.setUser("sa");
        return dataSource;
    }

    // The same settings as application.properties.
    private void migrate(DataSource dataSource) {
        Flyway.configure().dataSource(dataSource).baselineOnMigrate(true).baselineVersion("0").load().migrate();
    }

    private void execute(DataSource dataSource, String... statements) throws SQLException {
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            for (String sql : statements) {
                statement.execute(sql);
            }
        }
    }

    private List<String> rows(DataSource dataSource, String sql) throws SQLException {
        List<String> rows = new ArrayList<>();
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement();
                ResultSet result = statement.executeQuery(sql)) {
            while (result.next()) {
                rows.add(result.getString(1));
            }
        }
        return rows;
    }

    // The V4 tables as Hibernate wrote them, with url still at the varchar(255) it never widened.
    private void createHibernateSchema(DataSource dataSource) throws SQLException {
        execute(dataSource,
                "create table users (id bigint generated by default as identity primary key, "
                        + "created_at timestamp(6) with time zone not null, password_hash varchar(255) not null, "
                        + "username varchar(255) not null unique, email varchar(255), name varchar(255))",
                "create table jobs (id bigint generated by default as identity primary key, comp_max integer, "
                        + "comp_min integer, company varchar(255) not null, created_at timestamp(6) with time zone not null, "
                        + "current_stage varchar(255) not null, location varchar(255), outcome varchar(255) not null, "
                        + "role varchar(255) not null, url varchar(255), owner_id bigint not null references users (id), "
                        + "source_category varchar(255) not null, interview_phase varchar(255), city varchar(100))",
                "create table password_reset_tokens (id bigint generated by default as identity primary key, "
                        + "expires_at timestamp(6) with time zone not null, token_hash varchar(255) not null unique, "
                        + "used_at timestamp(6) with time zone, user_id bigint not null)");
    }

    @Test
    void anExistingDatabaseKeepsItsJobsAndPutsEachAccountsJobsInOneSeason() throws SQLException {
        DataSource dataSource = freshDatabase();
        createHibernateSchema(dataSource);
        execute(dataSource,
                "insert into users (id, created_at, password_hash, username) values (1, now(), 'h', 'ana'), (2, now(), 'h', 'ben')",
                "insert into jobs (company, role, owner_id, source_category, current_stage, outcome, created_at) values "
                        + "('A', 'Eng', 1, 'SELF_APPLIED', 'RESUME_CHECK', 'ACTIVE', now()), "
                        + "('B', 'Eng', 1, 'SELF_APPLIED', 'RESUME_CHECK', 'ACTIVE', now()), "
                        + "('C', 'Eng', 2, 'SELF_APPLIED', 'RESUME_CHECK', 'ACTIVE', now())");

        migrate(dataSource);

        assertThat(rows(dataSource, "select count(*) from jobs")).containsExactly("3");
        assertThat(rows(dataSource, "select owner_id || ':' || name from seasons order by owner_id"))
                .containsExactly("1:My job hunt", "2:My job hunt");
        assertThat(rows(dataSource, "select count(*) from jobs j join seasons s on s.id = j.season_id "
                + "where s.owner_id = j.owner_id")).containsExactly("3");
        assertThat(rows(dataSource, "select count(*) from users u join seasons s on s.id = u.active_season_id "
                + "where s.owner_id = u.id")).containsExactly("2");
        // Version 0, which a token from before carries implicitly, so nobody is signed out by the upgrade.
        assertThat(rows(dataSource, "select distinct session_version from users")).containsExactly("0");
        // The widened column takes a posting URL past 255 characters.
        execute(dataSource, "update jobs set url = '" + "x".repeat(400) + "' where company = 'A'");
    }

    @Test
    void aFreshDatabaseGetsTheWholeSchemaAndASecondStartChangesNothing() throws SQLException {
        DataSource dataSource = freshDatabase();

        migrate(dataSource);
        migrate(dataSource);

        assertThat(rows(dataSource, "select \"version\" from \"flyway_schema_history\" where \"version\" is not null order by \"installed_rank\""))
                .containsExactlyElementsOf(migrationVersions());
    }

    // Read from the files, so a new migration is covered without touching this test.
    private static List<String> migrationVersions() {
        try {
            return Arrays.stream(new PathMatchingResourcePatternResolver().getResources("classpath:db/migration/V*__*.sql"))
                    .map(file -> file.getFilename().substring(1, file.getFilename().indexOf("__")))
                    .sorted(Comparator.comparingInt(Integer::parseInt))
                    .toList();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
